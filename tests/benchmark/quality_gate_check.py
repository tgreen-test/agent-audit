#!/usr/bin/env python3
"""
Unified quality gate check for agent-audit benchmark.

Supports:
- Layer 1: synthetic sample precision/recall (overall + per-ASI)
- Layer 2: multi-target scan stability (owasp_coverage, max_scan_time)
- Agent-Vuln-Bench: real vulnerability detection with regression tracking

Layer 2 results file: results/layer2.json (generated by run_benchmark.py)

Usage:
  python tests/benchmark/quality_gate_check.py --config tests/benchmark/gates.yaml --results results/
  python tests/benchmark/quality_gate_check.py --layers layer1     # only what this job measured

Thresholds live in exactly one place: tests/benchmark/gates.yaml. Two tiers —
`thresholds` is the ratchet and blocks; `target` is aspirational and is reported
without blocking.

Two things this script will NOT do, both added 2026-08-11 after each was measured
exiting 0 (NIGHT_RUN_LEDGER.md § W38):

  - **Gate on a stale results file.** `results/layer1.json` is committed, so it is
    present in every checkout whether or not anything measured it. A file written before
    the corpus changed passed the ratchet and reported success about a tree that no
    longer existed. Layer 1 results must now carry a provenance stamp naming the corpus
    and scanner they came from, and it must match the tree being checked.
  - **Pass because nothing was measured.** A missing results file for an enabled,
    `blocking: true` layer used to report SKIP, which is not counted as a failure — so an
    empty results directory exited 0. It is now a FAIL. Use `--layers` to tell the script
    which layers this job is responsible for, rather than letting silence stand in for
    success.

Exit codes:
  0 = all passed
  1 = blocking failure
  2 = warnings only
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

# Same directory, no package here — running this file as a script puts its own directory
# on sys.path. Stated explicitly so the import does not depend on the caller's cwd.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import provenance  # noqa: E402


def _missing_results(layer_name: str, layer_config: dict, hint: str) -> tuple:
    """How to report a results file that is not there.

    A layer declared `enabled: true, blocking: true` and then not measured is a build
    that proved nothing. Reporting SKIP for it — which the summary does not count as a
    failure — is how an empty results directory used to exit 0. A layer that is enabled
    but non-blocking keeps the honest SKIP.
    """
    if layer_config.get("blocking", False):
        return (
            "FAIL",
            f"{layer_name} is enabled and blocking, but its results file is missing — "
            f"nothing measured it. Either produce it ({hint}) or exclude this layer from "
            f"this job with --layers.",
        )
    return ("SKIP", f"{layer_name} results not found ({hint})")


def check_layer1(config: dict, results_dir: Path) -> list:
    """Check Layer 1 thresholds (overall + per-ASI)."""
    issues = []
    layer1_config = config.get("layer1", {})
    if not layer1_config.get("enabled", True):
        return issues

    regenerate = "run precision_recall.py --output-json results/layer1.json"

    results_file = results_dir / "layer1.json"
    if not results_file.exists():
        issues.append(_missing_results("Layer 1", layer1_config, regenerate))
        return issues

    try:
        with open(results_file) as f:
            results = json.load(f)
    except Exception as e:
        issues.append(("FAIL", f"Layer 1 results invalid: {e}"))
        return issues

    # Is this file about THIS tree? Asked before any threshold, because a threshold
    # evaluated against the wrong corpus is not a weaker check, it is a different claim.
    try:
        stale = provenance.verify_stamp(
            results.get("provenance"),
            regenerate_hint=f"python3 tests/benchmark/precision_recall.py "
            f"--output-json {results_file}",
        )
    except provenance.ProvenanceError as e:
        issues.append(("FAIL", f"Layer 1 provenance could not be verified: {e}"))
        return issues

    if stale:
        for problem in stale:
            issues.append(("FAIL", f"Layer 1 results are not about this tree: {problem}"))
        # Deliberately no threshold evaluation below. Printing "precision 68.9% >= 66%"
        # underneath a staleness failure is how a number that describes nothing gets
        # quoted anyway.
        return issues

    # Check overall thresholds. `thresholds` is the ratchet and blocks CI;
    # `target` is aspirational and is reported below without ever blocking.
    thresholds = layer1_config.get("thresholds", {})
    if results.get("precision", 0) < thresholds.get("precision_min", 0):
        issues.append(("FAIL", f"Layer 1 precision {results.get('precision', 0):.1%} < {thresholds.get('precision_min', 0):.0%}"))
    if results.get("recall", 0) < thresholds.get("recall_min", 0):
        issues.append(("FAIL", f"Layer 1 recall {results.get('recall', 0):.1%} < {thresholds.get('recall_min', 0):.0%}"))
    if results.get("f1_score", 0) < thresholds.get("f1_min", 0):
        issues.append(("FAIL", f"Layer 1 F1 {results.get('f1_score', 0):.2%} < {thresholds.get('f1_min', 0):.0%}"))

    # Check per-ASI recall (only if per_asi exists in results)
    per_asi_results = results.get("per_asi", {})
    per_asi_thresholds = layer1_config.get("per_asi_recall_min", {})

    if per_asi_results and per_asi_thresholds:
        for asi, min_recall in per_asi_thresholds.items():
            asi_data = per_asi_results.get(asi, {})
            actual_recall = asi_data.get("recall", 0)
            if actual_recall < min_recall:
                issues.append((
                    "FAIL",
                    f"Layer 1 {asi} recall {actual_recall:.1%} < {min_recall:.0%}"
                ))

    # Report distance to the aspirational target. INFO never blocks: see the
    # forensics in gates.yaml for why these numbers are not a standard.
    target = layer1_config.get("target", {})
    for key, label, fmt in (
        ("precision_min", "precision", "precision"),
        ("recall_min", "recall", "recall"),
        ("f1_min", "F1", "f1_score"),
    ):
        if key in target:
            actual = results.get(fmt, 0)
            if actual < target[key]:
                issues.append((
                    "INFO",
                    f"Layer 1 {label} {actual:.1%} below target {target[key]:.0%} "
                    f"(aspirational, non-blocking)"
                ))

    return issues


def check_layer2(config: dict, results_dir: Path) -> list:
    """Check Layer 2 thresholds (owasp_coverage, max_scan_time)."""
    issues = []
    layer2_config = config.get("layer2", {})
    if not layer2_config.get("enabled", True):
        return issues

    results_file = results_dir / "layer2.json"
    if not results_file.exists():
        issues.append(_missing_results("Layer 2", layer2_config, "run run_benchmark.py"))
        return issues

    try:
        with open(results_file) as f:
            results = json.load(f)
    except Exception as e:
        issues.append(("FAIL", f"Layer 2 results invalid: {e}"))
        return issues

    thresholds = layer2_config.get("thresholds", {})
    is_blocking = layer2_config.get("blocking", False)

    # Check OWASP coverage
    owasp_coverage_min = thresholds.get("owasp_coverage_min", 0)
    actual_coverage = results.get("owasp_coverage", 0)
    if actual_coverage < owasp_coverage_min:
        level = "FAIL" if is_blocking else "WARN"
        issues.append((level, f"Layer 2 OWASP coverage {actual_coverage} < {owasp_coverage_min}"))

    # Check max scan time
    max_scan_time = thresholds.get("max_scan_time_seconds", float("inf"))
    actual_max_time = results.get("max_scan_time_seconds", 0)

    # Also check per_target if available
    per_target = results.get("per_target", [])
    for target in per_target:
        target_time = target.get("scan_duration_seconds", 0)
        if target_time > max_scan_time:
            actual_max_time = max(actual_max_time, target_time)

    if actual_max_time > max_scan_time:
        issues.append(("WARN", f"Layer 2 max scan time {actual_max_time:.1f}s > {max_scan_time}s"))

    return issues


def check_avb(config: dict, results_dir: Path) -> list:
    """Check Agent-Vuln-Bench thresholds."""
    issues = []
    avb_config = config.get("agent_vuln_bench", {})
    if not avb_config.get("enabled", True):
        return issues

    # Prefer single-file CI output, then directory results
    results_file = results_dir / "avb_results.json"
    if not results_file.exists():
        results_file = results_dir / "latest" / "results.json"
    if not results_file.exists():
        issues.append(_missing_results(
            "Agent-Vuln-Bench",
            avb_config,
            "run run_eval.py --output results/avb_results.json",
        ))
        return issues

    try:
        with open(results_file) as f:
            raw = json.load(f)
    except Exception as e:
        issues.append(("FAIL", f"AVB results invalid: {e}"))
        return issues

    # AVB results carry no provenance stamp yet, so the staleness hole Layer 1 just
    # closed is still open here. Reported rather than enforced: the AVB harness writes
    # this file and stamping it is a change to that harness, not to this gate. Recorded
    # as a follow-up in DECISIONS.md rather than left as a silent asymmetry.
    if "provenance" not in raw:
        issues.append((
            "INFO",
            f"Agent-Vuln-Bench results at {results_file} carry no provenance stamp — "
            "unlike Layer 1, nothing here can tell a current measurement from a stale "
            "one (DECISIONS.md, AVB provenance follow-up)",
        ))

    # Handle both CI format (overall, set_A) and multi-tool format (tool_name.metrics)
    if "overall" in raw:
        overall = raw.get("overall", {})
        recall = overall.get("recall", 0)
        precision = overall.get("precision", 0)
    else:
        first_tool = next(iter(raw), None)
        if first_tool and isinstance(raw.get(first_tool), dict):
            metrics = raw[first_tool].get("metrics", raw[first_tool])
            recall = metrics.get("recall", 0)
            precision = metrics.get("precision", 0)
        else:
            recall = raw.get("recall", 0)
            precision = raw.get("precision", 0)

    thresholds = avb_config.get("thresholds", {})
    min_recall = thresholds.get("overall_recall_min", 0)
    if recall < min_recall:
        issues.append(("FAIL", f"AVB recall {recall:.1%} < {min_recall:.0%}"))

    for set_key in ("a", "b", "c"):
        key = f"set_{set_key}_recall_min"
        if key not in thresholds:
            continue
        set_data = raw.get(f"set_{set_key.upper()}", {})
        if isinstance(set_data, dict):
            actual = set_data.get("recall", 0)
        else:
            actual = 0
        if actual < thresholds[key]:
            issues.append(("FAIL", f"AVB Set {set_key.upper()} recall {actual:.1%} < {thresholds[key]:.0%}"))

    regression = raw.get("regression", {})
    if not regression.get("regression_free", True) and not avb_config.get("regression", {}).get("allow_regression", True):
        failing = regression.get("newly_failing", [])
        issues.append(("FAIL", f"AVB regression: {len(failing)} samples regressed: {failing[:5]}"))

    return issues


def main() -> int:
    parser = argparse.ArgumentParser(description="Unified quality gate check")
    parser.add_argument("--config", default="tests/benchmark/gates.yaml", help="Path to the gate config (single source of truth)")
    parser.add_argument("--results", default="results/", help="Directory containing layer1.json and avb_results.json")
    parser.add_argument(
        "--layers",
        default="all",
        help=(
            "Comma-separated layers this job is responsible for: layer1, layer2, "
            "agent_vuln_bench, or 'all' (default). A layer named here and not measured "
            "is a failure; a layer not named is not checked at all. Use this instead of "
            "letting a missing file mean 'passed'."
        ),
    )
    args = parser.parse_args()

    known_layers = ("layer1", "layer2", "agent_vuln_bench")
    if args.layers.strip() == "all":
        selected = set(known_layers)
    else:
        selected = {name.strip() for name in args.layers.split(",") if name.strip()}
        unknown = sorted(selected - set(known_layers))
        if unknown:
            print(
                f"Unknown layer(s): {', '.join(unknown)}. Known: {', '.join(known_layers)}",
                file=sys.stderr,
            )
            return 1

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"Config not found: {config_path}", file=sys.stderr)
        return 1

    with open(config_path) as f:
        config = yaml.safe_load(f)

    results_dir = Path(args.results)
    all_issues = []

    if "layer1" in selected:
        all_issues.extend(check_layer1(config, results_dir))
    if "layer2" in selected:
        all_issues.extend(check_layer2(config, results_dir))
    if "agent_vuln_bench" in selected:
        all_issues.extend(check_avb(config, results_dir))

    blocking = [i for i in all_issues if i[0] == "FAIL"]
    warnings = [i for i in all_issues if i[0] == "WARN"]
    skips = [i for i in all_issues if i[0] == "SKIP"]
    infos = [i for i in all_issues if i[0] == "INFO"]

    print("=" * 60)
    print("Quality Gate Results")
    print("=" * 60)
    print(f"  config: {config_path}")
    print(f"  results: {results_dir}")
    print(f"  layers checked: {', '.join(sorted(selected))}")
    for level, msg in all_issues:
        icon = {"FAIL": "❌", "WARN": "⚠️", "SKIP": "⏭️", "INFO": "ℹ️"}.get(level, "?")
        print(f"  {icon} [{level}] {msg}")
    if not all_issues:
        print("  ✅ All quality gates passed!")
    print(f"\nSummary: {len(blocking)} failures, {len(warnings)} warnings, "
          f"{len(skips)} skipped, {len(infos)} below target (non-blocking)")

    if blocking:
        print("\n🚫 QUALITY GATE BLOCKED — fix failures before merging")
        return 1
    if warnings:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
